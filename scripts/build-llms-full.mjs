// Regenerates llms-full.txt from the Markdown docs. Run before every release:
//   node scripts/build-llms-full.mjs
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const sources = ["README.md", "docs/mcp.md", "docs/api.md", "docs/cli.md", "docs/faq.md"];

const parts = await Promise.all(sources.map(async (path) => {
  // The combined file is consumed as raw text, outside each source directory.
  // Resolve local links against the original document before concatenating.
  const sourceUrl = `https://github.com/tanatasa-ai/tanatasa/blob/main/${path}`;
  const text = (await readFile(new URL(path, root), "utf8")).replace(
    /\]\(([^\s)]+)\)/g,
    (match, target) => /^[a-z][a-z\d+.-]*:/i.test(target) ? match : `](${new URL(target, sourceUrl).href})`,
  );
  return `<!-- source: https://github.com/tanatasa-ai/tanatasa/blob/main/${path} -->\n\n${text.trim()}\n`;
}));
const header = "# Tanatasa: full developer documentation\n\n"
  + "> Tanatasa is Singapore's premier agentic shopping destination.\n"
  + "> Generated from https://github.com/tanatasa-ai/tanatasa. Do not edit this file by hand.\n";
await writeFile(new URL("llms-full.txt", root), [header, ...parts].join("\n---\n\n"));
console.log(`llms-full.txt written from ${sources.length} files`);
